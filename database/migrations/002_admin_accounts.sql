CREATE TABLE IF NOT EXISTS west_admin_accounts (
  id INT AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  password_hash VARCHAR(161) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

ALTER TABLE west_admin_sessions
  ADD COLUMN IF NOT EXISTS admin_id INT DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS legacy_email VARCHAR(255) DEFAULT NULL;
